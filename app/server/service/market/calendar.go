package market

import "time"

func CalendarID(exchange string) string {
	if exchange == "HKEX" {
		return "HKEX"
	}
	return "CN"
}

func IsHoliday(calendarID, date string) bool {
	if calendarID == "HKEX" {
		_, ok := hkHolidays[date]
		return ok
	}
	_, ok := cnHolidays[date]
	return ok
}

func IsWeekend(date string) bool {
	t, err := time.Parse("2006-01-02", date)
	if err != nil {
		return false
	}
	w := t.Weekday()
	return w == time.Saturday || w == time.Sunday
}

func IsTradingDay(calendarID, date string) bool {
	return !IsWeekend(date) && !IsHoliday(calendarID, date)
}

func PrevTradingDay(calendarID, date string) string {
	t, err := time.Parse("2006-01-02", date)
	if err != nil {
		return date
	}
	for i := 0; i < 20; i++ {
		t = t.AddDate(0, 0, -1)
		d := t.Format("2006-01-02")
		if IsTradingDay(calendarID, d) {
			return d
		}
	}
	return date
}

// LastCompleteSession is a conservative exchange-close approximation, not a feed delay claim.
func LastCompleteSession(calendarID string, now time.Time) string {
	loc := time.FixedZone("CST", 8*3600)
	local := now.In(loc)
	closeHour, closeMin := 15, 30
	if calendarID == "HKEX" {
		closeHour, closeMin = 16, 20
	}
	d := local.Format("2006-01-02")
	closed := local.Hour() > closeHour || (local.Hour() == closeHour && local.Minute() >= closeMin)
	if closed && IsTradingDay(calendarID, d) {
		return d
	}
	if IsTradingDay(calendarID, d) {
		return PrevTradingDay(calendarID, d)
	}
	return PrevTradingDay(calendarID, d)
}

func NextTradingDay(calendarID, date string) string {
	t, err := time.Parse("2006-01-02", date)
	if err != nil {
		return date
	}
	for i := 0; i < 15; i++ {
		t = t.AddDate(0, 0, 1)
		d := t.Format("2006-01-02")
		if IsTradingDay(calendarID, d) {
			return d
		}
	}
	return date
}

